package pw.binom.db.duckdb

/**
 * Настройки открытия базы.
 *
 * Отдельный тип, а не длинный список параметров конструктора: у DuckDB
 * десятки настроек (потоки, память, temp-каталог, доступ к файлам), и они
 * будут добавляться. `copy()` дешевле, чем менять сигнатуру конструктора
 * в каждом релизе.
 *
 * [path] == null — база в памяти. Это самый частый режим для аналитики
 * «загрузил Parquet, посчитал, забыл».
 */
data class DuckDbConfig(
    /** Путь к файлу базы; `null` — in-memory. */
    val path: String? = null,
    /** Только чтение (имеет смысл для файлового пути). */
    val readOnly: Boolean = false,
    /**
     * Открывать базу при старте. Если `false`, соединение откроется на
     * первом запросе — нужно, чтобы конструкция объекта не падала на
     * отсутствующей `.so`.
     */
    val autoOpen: Boolean = true,
)
